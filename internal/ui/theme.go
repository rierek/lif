// Themes returns every bundled flavour, keyed by name.
func Themes() map[string]Theme { return themes }

// ThemeByName looks up a flavour, case-insensitively — the same convention
// ResolveColor already applies to tone names (see styles.go), so "Mocha"
// and "mocha" resolve to the same flavour instead of the config lookup
// silently disagreeing with the colour-name lookup on case sensitivity.
func ThemeByName(name string) (Theme, bool) {
	t, ok := themes[strings.ToLower(name)]
	return t, ok
}

// IsValidTheme reports whether a name selects a bundled flavour. An empty
// name is valid and means "not configured": DefaultTheme applies.
//
// SetTheme deliberately ignores an unknown name so a typo degrades to the
// default instead of stripping colour from every command. That tolerance
// makes the typo invisible, which is why `lif check` validates the name
// through this predicate.
func IsValidTheme(name string) bool {
	if name == "" {
		return true
	}
	_, ok := ThemeByName(name)
	return ok
}

// DefaultTheme is Mocha, the flavour the CLI ships with.
func DefaultTheme() Theme { return themes["mocha"] }

// PaletteCSS renders every bundled flavour as CSS custom properties, one
// :root[data-flavour='<name>'] block per flavour with a --ctp-<tone> line per
// tone. frontend/src/lib/catppuccin.css is this output, written by
// `go generate ./internal/ui`, so the web UI never carries a hand-copied
// palette. Flavours and tones come out in a fixed order to keep the file
// stable under regeneration.
func PaletteCSS() string {
	var b strings.Builder
	b.WriteString("/* Generated by go generate ./internal/ui from internal/ui/theme.go. DO NOT EDIT. */\n")
	for _, name := range []string{"latte", "frappe", "macchiato", "mocha"} {
		colors := themes[name].Colors
		tones := make([]string, 0, len(colors))
		for tone := range colors {
			tones = append(tones, tone)
		}
		slices.Sort(tones)

		fmt.Fprintf(&b, "\n:root[data-flavour='%s'] {\n", name)
		for _, tone := range tones {
			fmt.Fprintf(&b, "  --ctp-%s: %s;\n", tone, colors[tone])
		}
		b.WriteString("}\n")
	}
	return b.String()
}
